"""Generate one stable native Ren'Py say statement per display paragraph."""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[1]

def generate(root=ROOT):
    source = root / 'game/demo/data'
    events = json.loads((source / 'scenario_events.json').read_text(encoding='utf-8'))
    paragraphs = json.loads((source / 'scenario_dialogue.json').read_text(encoding='utf-8'))
    grouped = {}
    for items in paragraphs.values():
        for item in items:
            first = item['ids'][0]
            key = first + ':paragraph:1' if len(item['ids']) > 1 else first
            for event_id in item['ids']:
                grouped[event_id] = key
    keys = {grouped.get(event['id'], event['id']) for items in events.values()
            for event in items if event['type'] == 'text'}
    lines = (source / 'pure_script.txt').read_text(encoding='utf-8-sig').splitlines()
    keys.update('file:demo/data/pure_script.txt:%d' % index
                for index, line in enumerate(line.strip() for line in lines if line.strip()))
    output = '# Generated by tools/generate_dialogue.py. Keep statement identities stable.\n\n'
    for key in sorted(keys):
        label = 'original_line_' + hashlib.sha256(key.encode('utf-8')).hexdigest()[:24]
        output += 'label %s:\n    narrator "[original_dynamic_text()]"\n    return\n\n' % label
    return output

if __name__ == '__main__':
    target = ROOT / 'game/demo_dialogue_lines.rpy'
    expected = generate()
    if '--check' in sys.argv:
        if not target.exists() or target.read_text(encoding='utf-8') != expected:
            raise SystemExit('Dialogue labels are stale. Run python tools/generate_dialogue.py')
        print('Stable dialogue labels: OK')
    else:
        target.write_text(expected, encoding='utf-8', newline='\n')
        print('Generated', target.name)
